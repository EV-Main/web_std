use std::{collections::BTreeSet, fmt::Write as _};

use serde_json::{Map, Value};

const SEGMENT: &str = "/// `s`, percent-encoded as one path segment.
fn segment(s: &str) -> String {
	s.bytes()
		.map(|b| match b {
			b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'-' | b'.' | b'_' | b'~' => (b as char).to_string(),
			b => format!(\"%{b:02X}\"),
		})
		.collect()
}

";

/// Rust source of one `async fn` per operation of `doc` (a document [`document`](super::document)
/// built), its schemas bound to the types of the same name under `types` (`"crate::dto"`).
///
/// The source is an `impl Client`, plus an enum for an operation whose 2xx answers differ. It names
/// what the including module holds: `Client`, with
/// `fn request(&self, reqwest::Method, &str) -> Result<reqwest::RequestBuilder, Error>` (the path
/// as the document has it) and `async fn send(reqwest::RequestBuilder) -> Result<reqwest::Response,
/// Error>` (a refusal is its `Err`), and `Error: From<reqwest::Error>`. How a request reaches the
/// service and what authenticates it is the module's.
///
/// A socket (`x-socket`) has no method. A schema it has no Rust type for (an inline object, a non-JSON request body) fails it.
pub fn rust_client(doc: &Value, types: &str) -> String {
	let schemas = doc["components"]["schemas"].as_object().cloned().unwrap_or_default();
	let paths = doc["paths"].as_object().expect("a document has paths");
	let mut enums = String::new();
	let mut methods = String::new();
	let mut segments = false;
	for (path, item) in paths {
		for method in ["get", "post", "put", "patch", "delete"] {
			let Some(op) = item.get(method).filter(|op| op["x-socket"] != true) else { continue };
			let op = Op {
				path,
				method,
				op,
				types,
				schemas: &schemas,
			};
			segments |= op.write(&mut methods, &mut enums);
		}
	}
	let mut out = String::from("// @generated by ev_lib::api::rust_client from the service's document.\n\n");
	if segments {
		out.push_str(SEGMENT);
	}
	out.push_str(&enums);
	writeln!(out, "impl Client {{{methods}}}").expect("writing to a String");
	out
}

struct Op<'a> {
	path: &'a str,
	method: &'a str,
	op: &'a Value,
	types: &'a str,
	schemas: &'a Map<String, Value>,
}
impl Op<'_> {
	fn id(&self) -> &str {
		self.op["operationId"].as_str().expect("document() names every operation")
	}

	/// Whether a string is a path segment of it.
	fn write(&self, methods: &mut String, enums: &mut String) -> bool {
		let id = self.id();
		let mut in_path = Vec::new();
		let mut queried = Vec::new();
		let mut args = Vec::new();
		let mut query = Vec::new();
		let mut headers = Vec::new();
		let mut path = self.path.to_owned();
		let mut segments = false;
		for p in self.op["parameters"].as_array().into_iter().flatten() {
			let name = p["name"].as_str().expect("a parameter has a name");
			let required = p["required"].as_bool() == Some(true);
			let arg = ident(name);
			let ty = self.ty(&p["schema"], !required);
			match p["in"].as_str() {
				Some("path") => {
					let ty = self.primitive(&p["schema"]);
					let at = self.path.find(&format!("{{{name}}}")).unwrap_or_else(|| panic!("{id}: {name} is in its path"));
					path = path.replace(&format!("{{{name}}}"), "{}");
					in_path.push(match ty.taken {
						Taken::Str => {
							segments = true;
							(at, format!("{arg}: &str"), format!("segment({arg})"))
						}
						_ => (at, format!("{arg}: {}", ty.owned), arg),
					});
				}
				Some("query") => {
					queried.push(format!("{arg}: {}", optional(&ty.arg(""), required)));
					query.push((name.to_owned(), arg, optional(&ty.arg("'a "), required), required, matches!(ty.taken, Taken::Copied)));
				}
				Some("header") => {
					let value = match ty.taken {
						Taken::Str => "v",
						_ => "v.to_string()",
					};
					args.push(format!("{arg}: {}", optional(&ty.arg(""), required)));
					headers.push(match required {
						true => format!("\t\treq = req.header({name:?}, {{ let v = {arg}; {value} }});\n"),
						false => format!("\t\tif let Some(v) = {arg} {{\n\t\t\treq = req.header({name:?}, {value});\n\t\t}}\n"),
					});
				}
				other => panic!("{id}: a parameter in {other:?} is not generated"),
			}
		}
		in_path.sort();
		args = in_path.iter().map(|(_, decl, _)| decl.clone()).chain(queried).chain(args).collect();
		let body = match self.op.get("requestBody") {
			None => None,
			Some(b) => {
				let schema = b["content"]
					.get("application/json")
					.unwrap_or_else(|| panic!("{id}: a request body other than JSON is not generated"))["schema"]
					.clone();
				let required = b["required"].as_bool() == Some(true);
				args.push(format!("body: {}", optional(&format!("&{}", self.ty(&schema, false).owned), required)));
				Some(required)
			}
		};
		let unique: BTreeSet<&str> = args.iter().map(|a| a.split(':').next().expect("split yields one item")).collect();
		assert_eq!(unique.len(), args.len(), "{id}: two arguments of one name");
		let answers = self.answers();
		let answer = match answers.iter().all(|(_, a)| a.ty() == answers[0].1.ty()) {
			true => answers[0].1.ty(),
			false => {
				self.write_enum(enums, &answers);
				pascal(id)
			}
		};
		let summary = self.op["summary"].as_str().unwrap_or_else(|| panic!("{id}: document() gives every operation a summary"));
		let method = self.method.to_uppercase();
		write!(
			methods,
			"\n\t/// {summary}\n\t///\n\t/// `{method} {}`\n\tpub async fn {id}(&self{}) -> Result<{answer}, Error> {{\n",
			self.path,
			args.iter().map(|a| format!(", {a}")).collect::<String>()
		)
		.expect("writing to a String");
		let path = match in_path.is_empty() {
			true => format!("{path:?}"),
			false => format!("&format!({path:?}, {})", in_path.iter().map(|(_, _, expr)| expr.as_str()).collect::<Vec<_>>().join(", ")),
		};
		let mutable = match headers.is_empty() {
			true => "",
			false => "mut ",
		};
		write!(methods, "\t\tlet {mutable}req = self.request(reqwest::Method::{method}, {path})?").expect("writing to a String");
		if !query.is_empty() {
			let lifetime = match query.iter().all(|q| q.4) {
				true => "",
				false => "<'a>",
			};
			let fields: String = query
				.iter()
				.map(|(name, arg, ty, required, _)| {
					let rename = match name == arg.trim_start_matches("r#") {
						true => String::new(),
						false => format!("\t\t\t\t#[serde(rename = {name:?})]\n"),
					};
					let skip = match required {
						true => "",
						false => "\t\t\t\t#[serde(skip_serializing_if = \"Option::is_none\")]\n",
					};
					format!("{rename}{skip}\t\t\t\t{arg}: {ty},\n")
				})
				.collect();
			let built: Vec<&str> = query.iter().map(|q| q.1.as_str()).collect();
			write!(
				methods,
				".query(&{{\n\t\t\t#[derive(serde::Serialize)]\n\t\t\tstruct Query{lifetime} {{\n{fields}\t\t\t}}\n\t\t\tQuery {{ {} }}\n\t\t}})",
				built.join(", ")
			)
			.expect("writing to a String");
		}
		if body.is_some() {
			methods.push_str(".json(body)");
		}
		methods.push_str(";\n");
		for h in &headers {
			methods.push_str(h);
		}
		match answers.len() == 1 || answer != pascal(id) {
			true => match answers[0].1 {
				Answer::Unit => writeln!(methods, "\t\tSelf::send(req).await?;\n\t\tOk(())\n\t}}"),
				ref a => writeln!(methods, "\t\tlet res = Self::send(req).await?;\n\t\tOk({})\n\t}}", a.decode()),
			},
			false => {
				let arms: String = answers
					.iter()
					.map(|(status, a)| match a {
						Answer::Unit => format!("\t\t\t{status} => {answer}::{},\n", reason(*status)),
						a => format!("\t\t\t{status} => {answer}::{}({}),\n", reason(*status), a.decode()),
					})
					.collect();
				writeln!(
					methods,
					"\t\tlet res = Self::send(req).await?;\n\t\tOk(match res.status().as_u16() {{\n{arms}\t\t\ts => panic!(\"{id}: {{s}} is no answer of its document\"),\n\t\t}})\n\t}}"
				)
			}
		}
		.expect("writing to a String");
		segments
	}

	fn answers(&self) -> Vec<(u16, Answer)> {
		let id = self.id();
		let answers: Vec<(u16, Answer)> = self.op["responses"]
			.as_object()
			.unwrap_or_else(|| panic!("{id}: an operation answers"))
			.iter()
			.filter_map(|(status, r)| {
				let status: u16 = status.parse().ok()?; // `default` is no 2xx
				(200..300).contains(&status).then(|| {
					let answer = match r["content"].as_object() {
						None => Answer::Unit,
						Some(c) => match c.get("application/json") {
							Some(json) => Answer::Json(self.ty(&json["schema"], false).owned),
							None => Answer::Bytes,
						},
					};
					(status, answer)
				})
			})
			.collect();
		assert!(!answers.is_empty(), "{id}: a socket or an operation without a 2xx answer is not generated");
		answers
	}

	fn write_enum(&self, enums: &mut String, answers: &[(u16, Answer)]) {
		let id = self.id();
		let variants: String = answers
			.iter()
			.map(|(status, a)| match a {
				Answer::Unit => format!("\t/// `{status}`\n\t{},\n", reason(*status)),
				a => format!("\t/// `{status}`\n\t{}({}),\n", reason(*status), a.ty()),
			})
			.collect();
		writeln!(enums, "/// What [`Client::{id}`] answered.\n#[derive(Debug)]\npub enum {} {{\n{variants}}}\n", pascal(id)).expect("writing to a String");
	}

	/// A path parameter's type, through a `$ref` to what it is on the wire.
	fn primitive(&self, schema: &Value) -> Ty {
		match schema.get("$ref").and_then(Value::as_str) {
			Some(r) => self.primitive(&self.schemas[r.trim_start_matches("#/components/schemas/")]),
			None => self.ty(schema, false),
		}
	}

	/// `schema`'s Rust type; `optional`: `null` is the parameter being left out, not a value of it.
	fn ty(&self, schema: &Value, optional: bool) -> Ty {
		let id = self.id();
		if let Some(r) = schema.get("$ref").and_then(Value::as_str) {
			let name = r.strip_prefix("#/components/schemas/").unwrap_or_else(|| panic!("{id}: {r} is not a schema of the document"));
			// what `document()` names a type whose request schema differs from its answer's
			let name = name.strip_suffix("Input").filter(|n| self.schemas.contains_key(*n)).unwrap_or(name);
			return Ty {
				owned: format!("{}::{name}", self.types),
				taken: Taken::Borrowed,
			};
		}
		for union in ["anyOf", "oneOf"] {
			if let Some(variants) = schema.get(union).and_then(Value::as_array) {
				let (null, other): (Vec<&Value>, Vec<&Value>) = variants.iter().partition(|v| v["type"] == "null");
				assert!(null.len() == 1, "{id}: no Rust type for {schema}");
				assert!(other.len() == 1, "{id}: no Rust type for {schema}");
				return self.nullable(self.ty(other[0], false), optional);
			}
		}
		let ty = match &schema["type"] {
			Value::Array(t) => {
				let other: Vec<&Value> = t.iter().filter(|t| *t != "null").collect();
				assert!(t.len() == 2, "{id}: no Rust type for {schema}");
				assert!(other.len() == 1, "{id}: no Rust type for {schema}");
				let mut inner = schema.clone();
				inner["type"] = other[0].clone();
				return self.nullable(self.ty(&inner, false), optional);
			}
			Value::String(t) => t.as_str(),
			Value::Null if schema.as_object().is_some_and(|o| o.keys().all(|k| k == "description")) || *schema == Value::Bool(true) => {
				return Ty {
					owned: "serde_json::Value".into(),
					taken: Taken::Borrowed,
				};
			}
			_ => panic!("{id}: no Rust type for {schema}"),
		};
		let copied = |owned: &str| Ty {
			owned: owned.into(),
			taken: Taken::Copied,
		};
		match (ty, schema["format"].as_str()) {
			("string", _) => Ty {
				owned: "String".into(),
				taken: Taken::Str,
			},
			("boolean", _) => copied("bool"),
			("number", Some("float")) => copied("f32"),
			("number", _) => copied("f64"),
			("integer", Some(f @ ("int8" | "int16" | "int32" | "int64" | "uint8" | "uint16" | "uint32" | "uint64"))) => copied(&f.replace("int", "i").replace("ui", "u")),
			("integer", Some("uint")) => copied("usize"),
			("integer", Some("int")) => copied("isize"),
			("integer", None) => copied("i64"),
			("array", _) => Ty {
				owned: format!("Vec<{}>", self.ty(&schema["items"], false).owned),
				taken: Taken::Borrowed,
			},
			("object", _) if schema["additionalProperties"].is_object() => Ty {
				owned: format!("std::collections::BTreeMap<String, {}>", self.ty(&schema["additionalProperties"], false).owned),
				taken: Taken::Borrowed,
			},
			_ => panic!("{id}: no Rust type for {schema}"),
		}
	}

	fn nullable(&self, inner: Ty, optional: bool) -> Ty {
		match optional {
			true => inner,
			false => Ty {
				owned: format!("Option<{}>", inner.owned),
				taken: Taken::Borrowed,
			},
		}
	}
}

/// A Rust type, and how an argument takes it.
struct Ty {
	owned: String,
	taken: Taken,
}
impl Ty {
	fn arg(&self, lifetime: &str) -> String {
		match self.taken {
			Taken::Copied => self.owned.clone(),
			Taken::Str => format!("&{lifetime}str"),
			Taken::Borrowed => format!("&{lifetime}{}", self.owned),
		}
	}
}

enum Taken {
	Copied,
	Str,
	Borrowed,
}

enum Answer {
	Unit,
	Json(String),
	Bytes,
}

impl Answer {
	fn ty(&self) -> String {
		match self {
			Self::Unit => "()".into(),
			Self::Json(t) => t.clone(),
			Self::Bytes => "Vec<u8>".into(),
		}
	}

	fn decode(&self) -> &'static str {
		match self {
			Self::Unit => "()",
			Self::Json(_) => "res.json().await?",
			Self::Bytes => "res.bytes().await?.to_vec()",
		}
	}
}

fn optional(ty: &str, required: bool) -> String {
	match required {
		true => ty.to_owned(),
		false => format!("Option<{ty}>"),
	}
}

/// `name` as a Rust identifier: `Idempotency-Key` is `idempotency_key`.
fn ident(name: &str) -> String {
	let ident = name.to_lowercase().replace('-', "_");
	assert!(ident.chars().all(|c| c.is_ascii_alphanumeric() || c == '_'), "{name} makes no Rust identifier");
	assert!(!ident.starts_with(|c: char| c.is_ascii_digit()), "{name} makes no Rust identifier");
	match syn_keyword(&ident) {
		true => format!("r#{ident}"),
		false => ident,
	}
}

fn syn_keyword(ident: &str) -> bool {
	matches!(
		ident,
		"as" | "async"
			| "await" | "break"
			| "const" | "continue"
			| "dyn" | "else"
			| "enum" | "extern"
			| "fn" | "for"
			| "gen" | "if"
			| "impl" | "in"
			| "let" | "loop"
			| "match" | "mod"
			| "move" | "mut"
			| "pub" | "ref"
			| "return"
			| "static"
			| "struct"
			| "trait" | "type"
			| "unsafe"
			| "use" | "where"
			| "while" | "yield"
	)
}

fn pascal(id: &str) -> String {
	id.split('_')
		.map(|w| {
			let mut c = w.chars();
			c.next().map(|f| f.to_ascii_uppercase().to_string() + c.as_str()).unwrap_or_default()
		})
		.collect()
}

fn reason(status: u16) -> &'static str {
	match status {
		200 => "Ok",
		201 => "Created",
		202 => "Accepted",
		203 => "NonAuthoritative",
		204 => "NoContent",
		206 => "PartialContent",
		s => panic!("{s} has no variant name"),
	}
}
