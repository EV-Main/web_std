/**
 * `evinvest-i18n-slices` — which message ids each part of a Next.js App
 * Router app renders on the client, read off its import graph.
 *
 * A client provider's `messages` are serialised into every page's RSC payload.
 * Slicing is what keeps that to the ids a page can actually ask for: the
 * provider in the root layout carries the {@link MessageSlices.shell}, and each
 * page's `I18nScope` adds its route's slice.
 *
 * The one rule every decision here follows: **a slice may carry an id it does
 * not need, never miss one it does.** A missing id renders English to a reader
 * of another language, silently. So every import is followed (type-only ones
 * excepted), every file below a `"use client"` boundary counts as client, and
 * anything the graph cannot account for — a local import that does not
 * resolve, an `import()` of a computed path in a file an entry reaches, a
 * `t()` with computed English anywhere — is an error rather than a skip.
 *
 * Syntactic, like the extractor: `ts.createSourceFile` per file, no program and
 * no type checker; `paths` come from the app's tsconfig.
 */
import { existsSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, extname, join, posix, relative, resolve, sep } from "node:path";

import ts from "typescript";

import type { MessageSlices } from "../slices.js";
import {
  callsIn,
  DEFAULT_EXCLUDE,
  type Entry,
  InputError,
  list,
  literal,
  parse,
  parseFlags,
  serialise,
  sourceFiles,
  where,
} from "./calls.js";

/**
 * A module of closed tables of copy keyed by a row name — `TIP_COPY[anchor](t)`.
 * Followed as an import, that module would put every row in every slice that
 * reaches it. A rule narrows it to the rows whose name appears as a string
 * literal in a file the entry reaches (server or client: a server page passing
 * `anchor="wallet.x"` to a client tip counts).
 *
 * A table is a top-level `const` initialised with an object literal holding
 * `t()` calls: `{ draft: t => t("Draft"), … } satisfies Record<State, …>`. Each
 * property's name is a row; the ids of the `t()` calls inside it are its copy.
 * The module's `t()` calls outside every table stay ordinary.
 */
export interface TableRule {
  /** Root-relative path of the module holding the tables. */
  table: string;
  /**
   * Root-relative files whose literals do not count — the module that lists
   * every row name (a typed registry of anchors) would otherwise select every row.
   */
  ignore?: readonly string[];
}

/** What {@link messageSlices} reads. */
export interface SliceOptions {
  /** The app's root: where `tsconfig.json` and the app directory are. */
  root: string;
  /** Root-relative App Router directory. Defaults to `app`, else `src/app`. */
  app?: string;
  /** The tsconfig whose `paths` and `baseUrl` resolve aliases. Defaults to `<root>/tsconfig.json` when present. */
  tsconfig?: string;
  /** Names skipped when listing every id for `serverOnly`; as for `collect`. */
  exclude?: readonly string[];
  tables?: readonly TableRule[];
}

/** The slices, plus everything the graph could not account for. */
export interface SliceResult {
  slices: MessageSlices;
  errors: string[];
}

/** The first line of the generated file, as a `"//"` member: JSON has no comments. */
export const SLICES_HEADER =
  "GENERATED by evinvest-i18n-slices from the app's import graph. Do not edit by hand: " +
  "run evinvest-i18n-slices; its --check fails CI when this file drifts from the code.";

/** Files Next renders as a route segment's own — a page, or what wraps or replaces one. */
const ENTRY =
  /^(page|layout|template|loading|error|not-found|forbidden|unauthorized|default|global-error|global-not-found)\.(tsx|ts|jsx|js)$/;
/** Of those, the one a page's `I18nScope` wraps; everything else renders outside it, so it is shell. */
const PAGE = /^page\.(tsx|ts|jsx|js)$/;
/** Parsed and followed; anything else that resolves (CSS, JSON, SVG) is a leaf. */
const CODE = /\.(tsx?|mts|cts|jsx?|mjs|cjs)$/;
/** Tried in this order after the bare path, as `moduleResolution: bundler` does. */
const EXTENSIONS = [".ts", ".tsx", ".mts", ".cts", ".d.ts", ".js", ".jsx", ".mjs", ".cjs"];
/** A `./x.js` specifier in TypeScript source names `./x.ts`. */
const JS_TO_TS: Readonly<Record<string, readonly string[]>> = {
  ".js": [".ts", ".tsx"],
  ".jsx": [".tsx"],
  ".mjs": [".mts"],
  ".cjs": [".cts"],
};

/** One parsed file: what it renders, what it says, whether it starts a client boundary. */
interface Module {
  client: boolean;
  source: ts.SourceFile | null;
  entries: Entry[];
  /** Unreadable `t()` calls: errors wherever the file is, as they are for `collect`. */
  callErrors: string[];
  /**
   * Imports of a computed path: errors only in a file an entry reaches, the one
   * place an unfollowed path could carry ids out of a slice.
   */
  importErrors: string[];
  literals: ReadonlySet<string>;
  /** Specifiers with the node they were read at; resolved on first traversal. */
  specifiers: { specifier: string; at: string }[];
}

interface Paths {
  /** Absolute directory `paths` targets are relative to. */
  base: string;
  /** `[prefix, suffix, targets]`, longest prefix first, as tsc tries them. */
  patterns: { prefix: string; suffix: string; wildcard: boolean; targets: string[] }[];
  /** Absolute `baseUrl`, which also resolves bare specifiers. */
  baseUrl: string | null;
}

type Resolution =
  | { kind: "local"; path: string }
  | { kind: "external" }
  | { kind: "unresolved"; alias?: string };

/**
 * Whether a bare specifier can name an npm package. `@/x` (an empty scope),
 * `~/x` and `#x` cannot: they only mean something through an alias — tsconfig
 * `paths`, a bundler alias, package.json `imports` — so one nothing here maps
 * is a local import the graph lost, not a package to stop at.
 */
const couldBePackage = (specifier: string): boolean =>
  specifier.startsWith("@") ? /^@[^/]+\/[^/]/.test(specifier) : !/^[~#]/.test(specifier);

const isFile = (path: string): boolean =>
  statSync(path, { throwIfNoEntry: false })?.isFile() ?? false;

const sortedArray = (ids: Iterable<string>): string[] => [...ids].sort();

/** `"use client"` among the directive prologue — the statements before the first non-string one. */
function startsClientBoundary(source: ts.SourceFile): boolean {
  for (const statement of source.statements) {
    if (!ts.isExpressionStatement(statement) || !ts.isStringLiteral(statement.expression)) return false;
    if (statement.expression.text === "use client") return true;
  }
  return false;
}

/** Runtime imports (static, re-exports, `import()`, `require`) and every string literal. */
function scan(path: string, source: ts.SourceFile): Pick<Module, "importErrors" | "literals" | "specifiers"> {
  const importErrors: string[] = [];
  const literals = new Set<string>();
  const specifiers: Module["specifiers"] = [];
  const add = (node: ts.Node, specifier: ts.Node | undefined, what: string) => {
    const text = specifier === undefined ? null : literal(specifier);
    // A computed path could load anything, and its ids would be in no slice.
    if (text === null)
      importErrors.push(`${where(path, source, node)}: ${what} of a non-literal path cannot be followed`);
    else specifiers.push({ specifier: text, at: where(path, source, node) });
  };
  const visit = (node: ts.Node) => {
    if (ts.isImportDeclaration(node)) {
      if (node.importClause?.isTypeOnly !== true) add(node, node.moduleSpecifier, "import");
    } else if (ts.isExportDeclaration(node)) {
      if (!node.isTypeOnly && node.moduleSpecifier !== undefined) add(node, node.moduleSpecifier, "export");
    } else if (ts.isImportEqualsDeclaration(node)) {
      if (!node.isTypeOnly && ts.isExternalModuleReference(node.moduleReference))
        add(node, node.moduleReference.expression, "import =");
    } else if (ts.isCallExpression(node)) {
      if (node.expression.kind === ts.SyntaxKind.ImportKeyword) add(node, node.arguments[0], "import()");
      else if (ts.isIdentifier(node.expression) && node.expression.text === "require")
        add(node, node.arguments[0], "require()");
    } else if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) {
      literals.add(node.text);
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
  return { importErrors, literals, specifiers };
}

/** `paths` and `baseUrl` of one tsconfig, `extends` followed. */
function readPaths(tsconfig: string): Paths {
  const read = ts.readConfigFile(tsconfig, ts.sys.readFile);
  if (read.error !== undefined)
    throw new InputError(`${tsconfig}: ${ts.flattenDiagnosticMessageText(read.error.messageText, "\n")}`);
  // Only the options are wanted: listing the project's files would walk the tree for nothing.
  const host: ts.ParseConfigHost = { ...ts.sys, readDirectory: () => [] };
  const { options } = ts.parseJsonConfigFileContent(read.config, host, dirname(tsconfig), undefined, tsconfig);
  // tsc records where an inherited `paths` was declared, which is what its targets are relative to.
  const declaredAt = options["pathsBasePath"];
  const base = options.baseUrl ?? (typeof declaredAt === "string" ? declaredAt : dirname(tsconfig));
  const patterns = Object.entries(options.paths ?? {})
    .map(([pattern, targets]) => {
      const star = pattern.indexOf("*");
      return star === -1
        ? { prefix: pattern, suffix: "", wildcard: false, targets }
        : { prefix: pattern.slice(0, star), suffix: pattern.slice(star + 1), wildcard: true, targets };
    })
    .sort((a, b) => b.prefix.length - a.prefix.length);
  return { base, patterns, baseUrl: options.baseUrl ?? null };
}

function createResolver(root: string, paths: Paths | null) {
  const toRoot = (abs: string) => relative(root, abs).split(sep).join("/");

  const find = (abs: string): string | null => {
    const ext = extname(abs);
    const swapped = (JS_TO_TS[ext] ?? []).map(to => abs.slice(0, -ext.length) + to);
    const candidates = [
      ...swapped,
      abs,
      ...EXTENSIONS.map(e => abs + e),
      ...EXTENSIONS.map(e => join(abs, `index${e}`)),
    ];
    const hit = candidates.find(isFile);
    return hit === undefined ? null : toRoot(hit);
  };

  return (from: string, raw: string): Resolution => {
    // A bundler query (`./icon.svg?url`) names the file before it. A leading `#`
    // is a subpath import (`#components/b`), not a fragment, so it stays.
    const specifier = raw.replace(/(?!^)[?#].*$/, "");
    const local = (abs: string): Resolution => {
      const path = find(abs);
      return path === null ? { kind: "unresolved" } : { kind: "local", path };
    };
    if (/^\.\.?(\/|$)/.test(specifier)) return local(resolve(root, dirname(from), specifier));
    if (specifier.startsWith("/")) return local(specifier);
    if (paths !== null) {
      for (const { prefix, suffix, wildcard, targets } of paths.patterns) {
        const matches = wildcard
          ? specifier.length >= prefix.length + suffix.length &&
            specifier.startsWith(prefix) &&
            specifier.endsWith(suffix)
          : specifier === prefix;
        if (!matches) continue;
        const capture = wildcard ? specifier.slice(prefix.length, specifier.length - suffix.length) : "";
        for (const target of targets) {
          const path = find(resolve(paths.base, target.replace("*", capture)));
          if (path !== null) return { kind: "local", path };
        }
        // A bare `*` maps everything, packages included; anything narrower
        // (`@/*`) is a promise that the specifier is ours, so a miss is a broken import.
        if (prefix !== "" || suffix !== "")
          return { kind: "unresolved" };
      }
      if (paths.baseUrl !== null) {
        const path = find(resolve(paths.baseUrl, specifier));
        if (path !== null) return { kind: "local", path };
      }
    }
    if (!couldBePackage(specifier))
      return {
        kind: "unresolved",
        alias:
          paths === null
            ? "it is an alias, not a package, and no tsconfig was read to map it"
            : "it is an alias, not a package, and the tsconfig's paths do not map it",
      };
    return { kind: "external" };
  };
}

/** Root-relative and POSIX, the shape every path in the result has. */
const normal = (path: string) => posix.normalize(path.split(sep).join("/"));

function appDirectory(root: string, app: string | undefined): string {
  if (app !== undefined) {
    if (!existsSync(join(root, app))) throw new InputError(`app directory ${join(root, app)} does not exist`);
    return normal(app);
  }
  const found = ["app", "src/app"].find(dir => existsSync(join(root, dir)));
  if (found === undefined) throw new InputError(`no app/ or src/app/ under ${root}; pass the app directory`);
  return found;
}

/** A table rule with its module's tables read. */
interface PreparedRule {
  table: string;
  ignore: ReadonlySet<string>;
  /** The module's ids called outside every table: carried whenever the module is. */
  ordinary: ReadonlySet<string>;
  rows: ReadonlyMap<string, ReadonlySet<string>>;
}

const unwrap = (node: ts.Expression): ts.Expression =>
  ts.isSatisfiesExpression(node) || ts.isAsExpression(node) || ts.isTypeAssertionExpression(node) || ts.isParenthesizedExpression(node)
    ? unwrap(node.expression)
    : node;

const rowName = (name: ts.PropertyName): string | null =>
  ts.isIdentifier(name) || ts.isPrivateIdentifier(name)
    ? name.text
    : ts.isComputedPropertyName(name)
      ? literal(name.expression)
      : name.text;

function prepare(rule: TableRule, path: string, source: ts.SourceFile): PreparedRule | string {
  // Reparsed on its own so `callsIn` reads exactly the calls under one row; its `where` is not used.
  const idsIn = (node: ts.Node): string[] => callsIn(path, parse(path, node.getText(source))).entries.map(e => e.id);
  const rows = new Map<string, Set<string>>();
  const tabled = new Map<string, number>();
  for (const statement of source.statements) {
    if (!ts.isVariableStatement(statement) || !(statement.declarationList.flags & ts.NodeFlags.Const)) continue;
    for (const declaration of statement.declarationList.declarations) {
      const init = declaration.initializer === undefined ? undefined : unwrap(declaration.initializer);
      if (init === undefined || !ts.isObjectLiteralExpression(init) || idsIn(init).length === 0) continue;
      for (const property of init.properties) {
        const body = ts.isPropertyAssignment(property)
          ? property.initializer
          : ts.isMethodDeclaration(property) || ts.isAccessor(property)
            ? property.body
            : undefined;
        const name = property.name === undefined ? null : rowName(property.name);
        // A row with no literal name can be selected by nothing, so its ids stay ordinary.
        if (body === undefined || name === null) continue;
        const ids = idsIn(body);
        rows.set(name, new Set([...(rows.get(name) ?? []), ...ids]));
        for (const id of ids) tabled.set(id, (tabled.get(id) ?? 0) + 1);
      }
    }
  }
  if (rows.size === 0)
    return `table rule for ${rule.table}: no top-level const in it is an object literal of t() copy`;
  // An id also called outside a table must stay carried with the module, so counts, not membership.
  const calls = new Map<string, number>();
  for (const { id } of callsIn(path, source).entries) calls.set(id, (calls.get(id) ?? 0) + 1);
  const ordinary = new Set([...calls].filter(([id, n]) => n > (tabled.get(id) ?? 0)).map(([id]) => id));
  return { table: path, ignore: new Set((rule.ignore ?? []).map(normal)), ordinary, rows };
}

/**
 * Which ids each entry renders on the client.
 *
 * - **Entries** are the App Router's own files under the app directory: every
 *   `page`, and the files that wrap or replace one — `layout`, `template`,
 *   `loading`, `error`, `not-found`, `forbidden`, `unauthorized`, `default`,
 *   `global-error`, `global-not-found`.
 * - **Client** is every file at or below a `"use client"` module on the path
 *   from an entry; its `t()` ids are the slice's.
 * - **`shell`** is every non-page entry's ids together: those render outside
 *   any page's `I18nScope` (a layout around it, an error boundary in its place),
 *   so the provider must carry them.
 * - **`routes`** maps each page to its ids minus the shell's.
 * - **`serverOnly`** is every id under `root` no slice carries.
 *
 * @throws For what the caller has to fix before anything can be read: a missing
 *   app directory or tsconfig.
 */
export function messageSlices(options: SliceOptions): SliceResult {
  const root = resolve(options.root);
  const app = appDirectory(root, options.app);
  const tsconfig = options.tsconfig ?? join(root, "tsconfig.json");
  if (options.tsconfig !== undefined && !existsSync(tsconfig)) throw new InputError(`${tsconfig} does not exist`);
  const resolveFrom = createResolver(root, existsSync(tsconfig) ? readPaths(tsconfig) : null);

  const modules = new Map<string, Module>();
  const load = (path: string): Module => {
    const known = modules.get(path);
    if (known !== undefined) return known;
    let module: Module;
    if (!CODE.test(path)) {
      module = {
        client: false,
        source: null,
        entries: [],
        callErrors: [],
        importErrors: [],
        literals: new Set(),
        specifiers: [],
      };
    } else {
      const source = parse(path, readFileSync(join(root, path), "utf8"));
      const calls = callsIn(path, source);
      const scanned = scan(path, source);
      module = {
        client: startsClientBoundary(source),
        source,
        entries: calls.entries,
        callErrors: calls.errors,
        importErrors: scanned.importErrors,
        literals: scanned.literals,
        specifiers: scanned.specifiers,
      };
    }
    modules.set(path, module);
    return module;
  };

  const edges = new Map<string, string[]>();
  const graphErrors = new Set<string>();
  const importsOf = (path: string): string[] => {
    const known = edges.get(path);
    if (known !== undefined) return known;
    const found: string[] = [];
    for (const { specifier, at } of load(path).specifiers) {
      const resolution = resolveFrom(path, specifier);
      if (resolution.kind === "local") found.push(resolution.path);
      else if (resolution.kind === "unresolved")
        graphErrors.add(
          `${at}: cannot resolve "${specifier}" — a local import the graph cannot follow` +
            (resolution.alias === undefined ? "" : ` (${resolution.alias})`),
        );
    }
    edges.set(path, found);
    return found;
  };

  /** Everything `starts` load, and the part of it that runs on the client. */
  const reach = (starts: readonly string[]) => {
    const all = new Set<string>();
    const client = new Set<string>();
    const seen = new Set<string>();
    const stack = starts.map(path => ({ path, inClient: false }));
    for (let next = stack.pop(); next !== undefined; next = stack.pop()) {
      const inClient = next.inClient || load(next.path).client;
      const id = `${inClient ? "c" : "s"}:${next.path}`;
      if (seen.has(id)) continue;
      seen.add(id);
      all.add(next.path);
      if (inClient) client.add(next.path);
      for (const path of importsOf(next.path)) stack.push({ path, inClient });
    }
    return { all, client };
  };

  // Every id under the root, read the way `collect` reads it: what no slice
  // carries is `serverOnly`, and an unreadable call anywhere is an error here too.
  const skip = new Set([...DEFAULT_EXCLUDE, ...(options.exclude ?? [])]);
  const listed = [...sourceFiles(root, skip, "")];
  const appFiles = listed.filter(path => path.startsWith(`${app}/`));
  const entries = appFiles.filter(path => ENTRY.test(posix.basename(path))).sort();
  const pages = entries.filter(path => PAGE.test(posix.basename(path)));
  const shellEntries = entries.filter(path => !PAGE.test(posix.basename(path)));

  const ruleErrors: string[] = [];
  const rules: PreparedRule[] = [];
  for (const rule of options.tables ?? []) {
    const table = normal(rule.table);
    if (!isFile(join(root, table))) {
      ruleErrors.push(`table rule: ${table} does not exist under ${root}`);
      continue;
    }
    const { source } = load(table);
    if (source === null) {
      ruleErrors.push(`table rule: ${table} is not source`);
      continue;
    }
    const prepared = prepare(rule, table, source);
    if (typeof prepared === "string") ruleErrors.push(prepared);
    else rules.push(prepared);
  }

  const idsOf = ({ all, client }: { all: ReadonlySet<string>; client: ReadonlySet<string> }) => {
    const ids = new Set<string>();
    for (const path of client) {
      const rule = rules.find(rule => rule.table === path);
      for (const { id } of load(path).entries) if (rule === undefined || rule.ordinary.has(id)) ids.add(id);
    }
    for (const rule of rules) {
      for (const path of all) {
        if (path === rule.table || rule.ignore.has(path)) continue;
        for (const value of load(path).literals) for (const id of rule.rows.get(value) ?? []) ids.add(id);
      }
    }
    return ids;
  };

  // Every file some entry loads: a computed import elsewhere (a test's
  // `await import(spec)`) feeds no slice, so it is no error here.
  const reachable = new Set<string>();
  const reachAndRecord = (starts: readonly string[]) => {
    const reached = reach(starts);
    for (const path of reached.all) reachable.add(path);
    return reached;
  };

  const shell = idsOf(reachAndRecord(shellEntries));
  const routes: Record<string, string[]> = {};
  const carried = new Set(shell);
  for (const page of pages) {
    const own = [...idsOf(reachAndRecord([page]))].filter(id => !shell.has(id));
    for (const id of own) carried.add(id);
    routes[page] = sortedArray(own);
  }

  for (const path of listed) load(path);
  const everyEntry = [...modules.values()].flatMap(module => module.entries);
  const serverOnly = sortedArray(new Set(everyEntry.map(e => e.id).filter(id => !carried.has(id))));

  const errors = [
    ...ruleErrors,
    ...[...modules.values()].flatMap(module => module.callErrors),
    ...[...reachable].flatMap(path => load(path).importErrors),
    ...graphErrors,
  ];
  return {
    slices: { shell: sortedArray(shell), routes, serverOnly },
    errors: [...new Set(errors)].sort(),
  };
}

/** The exact bytes the slices are written as — what `--check` compares against. */
export const serialiseSlices = (slices: MessageSlices): string =>
  serialise({ "//": SLICES_HEADER, ...slices });

const isRecord = (value: unknown): value is Record<string, unknown> =>
  typeof value === "object" && value !== null && !Array.isArray(value);

function strings(value: unknown): string[] | null {
  if (!Array.isArray(value)) return null;
  const found = value.filter((item): item is string => typeof item === "string");
  return found.length === value.length ? found : null;
}

/** `{ "tables": [{ "table", "ignore"? }] }`, checked field by field. */
function tablesFrom(raw: unknown, path: string): TableRule[] {
  const fail = (what: string) => new InputError(`${path}: ${what}`);
  if (!isRecord(raw)) throw fail("expected an object");
  const unknown = Object.keys(raw).filter(key => key !== "tables");
  if (unknown.length > 0) throw fail(`unknown field ${unknown.join(", ")}`);
  const tables = raw["tables"];
  if (tables === undefined) return [];
  if (!Array.isArray(tables)) throw fail(`"tables" must be an array`);
  return tables.map((rule: unknown, at): TableRule => {
    if (!isRecord(rule)) throw fail(`tables[${at}] must be an object`);
    const extra = Object.keys(rule).filter(key => !["table", "ignore"].includes(key));
    if (extra.length > 0) throw fail(`tables[${at}]: unknown field ${extra.join(", ")}`);
    const table = rule["table"];
    const ignore = rule["ignore"] === undefined ? [] : strings(rule["ignore"]);
    if (typeof table !== "string") throw fail(`tables[${at}].table must be a string`);
    if (ignore === null) throw fail(`tables[${at}].ignore must be an array of strings`);
    return { table, ignore };
  });
}

